const SPANISH_MONTHS = ['ene', 'feb', 'mar', 'abr', 'may', 'jun', 'jul', 'ago', 'sep', 'oct', 'nov', 'dic'];
const ENGLISH_MONTHS = ['Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun', 'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec'];
const SPANISH_MONTHS_LONG = ['enero', 'febrero', 'marzo', 'abril', 'mayo', 'junio', 'julio', 'agosto', 'septiembre', 'octubre', 'noviembre', 'diciembre'];
const ENGLISH_MONTHS_LONG = ['January', 'February', 'March', 'April', 'May', 'June', 'July', 'August', 'September', 'October', 'November', 'December'];

const exact = new Map<string, string>();
const patterns: { re: RegExp; en: string; literal: number; numeric: boolean[] }[] = [];
const escapeRe = (s: string) => s.replace(/[.*+?^$()|[\]\\]/g, '\\$&');
const HOLE = /\{#?\}/g;
for (const [es, en] of EN) {
  if (!/\{#?\}/.test(es)) exact.set(es, en);
  else {
    const source = escapeRe(es).replace(/\{\}/g, '(.+?)').replace(/\{#\}/g, '(-?[\\d.,]+)');
    const numeric = (es.match(HOLE) ?? []).map((h) => h === '{#}');
    patterns.push({ re: new RegExp(`^${source}$`), en, literal: es.replace(HOLE, '').length, numeric });
  }
}
// Las plantillas con más texto fijo (las más concretas) primero
patterns.sort((a, b) => b.literal - a.literal);
for (let k = 0; k < 12; k++) {
  exact.set(SPANISH_MONTHS_LONG[k], ENGLISH_MONTHS_LONG[k]);
}

const cache = new Map<string, string | null>();

/** Números del formato español al inglés: 12.500 → 12,500 y 0,4 → 0.4. */
const SPANISH_NUMBER = /\d{1,3}(?:\.\d{3})+(?:,\d+)?|\d+,\d+/g;
const englishNumbers = (s: string) =>
  s
    .replace(SPANISH_NUMBER, (n) => n.replace(/[.,]/g, (c) => (c === '.' ? ',' : '.')))
    // El español no separa los miles de cuatro cifras; el inglés sí (en dinero y cantidades, no en años)
    .replace(/\$(\d)(\d{3})(?!\d)/g, '$$$1,$2');
/** Una cantidad de un hueco {#}: además, 1500 → 1,500. */
const englishQuantity = (s: string) => englishNumbers(s).replace(/^(-?\d)(\d{3})$/, '$1,$2');

/** Traducción al inglés de un texto completo (sin espacios alrededor), o null si no está en el diccionario. */
function lookup(text: string): string | null {
  const hit = exact.get(text);
  if (hit !== undefined) return hit;
  const cached = cache.get(text);
  if (cached !== undefined) return cached;
  let out: string | null = null;
  // Sin letras (cifras, dinero, porcentajes): solo cambia el formato de los números
  if (!/\p{L}/u.test(text)) {
    const n = englishNumbers(text);
    if (n !== text) out = n;
  }
  // Fecha de la barra superior: «12 mar 2005»
  const date = /^(\d{1,2}) ([a-z]{3}) (\d{4})$/.exec(text);
  if (date && SPANISH_MONTHS.includes(date[2])) out = `${ENGLISH_MONTHS[SPANISH_MONTHS.indexOf(date[2])]} ${date[1]}, ${date[3]}`;
  // Lo que dice un vecino, entre comillas españolas
  const quote = /^«(.+)»$/.exec(text);
  if (out === null && quote) {
    const inner = lookup(quote[1]);
    if (inner !== null) out = `“${inner}”`;
  }
  for (const p of out !== null ? [] : patterns) {
    const m = p.re.exec(text);
    if (!m) continue;
    let k = 0;
    // Lo que cae en un hueco se traduce si se puede (un edificio, un rango...)
    out = p.en.replace(/\{(\d?)\}/g, (_, d: string) => {
      const g = d ? Number(d) : ++k;
      const piece = m[g] ?? '';
      if (p.numeric[g - 1]) return englishQuantity(piece);
      return lookup(piece) ?? piece;
    });
    break;
  }
  // Líneas compuestas («Rosa · Los Tilos · hace 7 días»): cada trozo por separado
  if (out === null && text.includes(' · ')) {
    const parts = text.split(' · ');
    const en = parts.map((part) => lookup(part) ?? part);
    if (en.some((part, k) => part !== parts[k])) out = en.join(' · ');
  }
  if (cache.size > 5_000) cache.clear();
  cache.set(text, out);
  return out;
}

/** Traduce un texto al inglés conservando los espacios de alrededor; si no se conoce, lo deja igual. */
export function translate(text: string, lang: Language = current): string {
  if (lang !== 'en') return text;
  const core = text.trim();
  if (!core) return text;
  const en = lookup(core);
  return en === null ? text : text.replace(core, en);
}

let current: Language = 'es';
const ATTRS = ['aria-label', 'data-tip', 'placeholder', 'title'] as const;
/** Textos originales (en español) de lo que se ha traducido, para poder volver. */
const originalText = new WeakMap<Text, string>();
const originalAttrs = new WeakMap<Element, Partial<Record<(typeof ATTRS)[number], string>>>();

function translateText(node: Text): void {
  const value = node.nodeValue ?? '';
  const original = originalText.get(node);
  if (original !== undefined && value === translate(original, 'en')) return; // ya está traducido
  const en = translate(value, 'en');
  if (en === value) return;
  originalText.set(node, value);
  node.nodeValue = en;
}

function translateAttrs(el: Element): void {
  for (const a of ATTRS) {
    const value = el.getAttribute(a);
    if (!value) continue;
    const saved = originalAttrs.get(el) ?? {};
    if (saved[a] !== undefined && value === translate(saved[a]!, 'en')) continue;
    const en = translate(value, 'en');
    if (en === value) continue;
    saved[a] = value;
    originalAttrs.set(el, saved);
    el.setAttribute(a, en);
  }
}

function walk(root: Node, fn: (n: Node) => void): void {
  fn(root);
  const it = document.createTreeWalker(root, NodeFilter.SHOW_ELEMENT | NodeFilter.SHOW_TEXT);
  for (let n = it.nextNode(); n; n = it.nextNode()) fn(n);
}

const visit = (n: Node) => {
  if (n.nodeType === Node.TEXT_NODE) translateText(n as Text);
  else if (n.nodeType === Node.ELEMENT_NODE) translateAttrs(n as Element);
};

/** Vuelve a poner los textos en español donde siguen como los dejó la traducción. */
function restore(root: Node): void {
  walk(root, (n) => {
    if (n.nodeType === Node.TEXT_NODE) {
      const t = n as Text;
      const original = originalText.get(t);
      if (original !== undefined && t.nodeValue === translate(original, 'en')) t.nodeValue = original;
      originalText.delete(t);
    } else if (n.nodeType === Node.ELEMENT_NODE) {
      const el = n as Element;
      const saved = originalAttrs.get(el);
      if (!saved) return;
      for (const a of ATTRS) if (saved[a] !== undefined && el.getAttribute(a) === translate(saved[a]!, 'en')) el.setAttribute(a, saved[a]!);
      originalAttrs.delete(el);
    }
  });
}

let observer: MutationObserver | null = null;

/** Cambia el idioma de la página: en inglés, traduce lo que hay y todo lo que aparezca después. */
export function setLanguage(lang: Language, root: HTMLElement = document.body): void {
  if (lang === current) return;
  current = lang;
  document.documentElement.lang = lang;
  if (lang === 'en') {
    walk(root, visit);
    observer ??= new MutationObserver((records) => {
      if (current !== 'en') return;
      for (const r of records) {
        if (r.type === 'characterData') translateText(r.target as Text);
        else if (r.type === 'attributes') translateAttrs(r.target as Element);
        else r.addedNodes.forEach((n) => walk(n, visit));
      }
    });
    observer.observe(root, { subtree: true, childList: true, characterData: true, attributes: true, attributeFilter: [...ATTRS] });
  } else {
    observer?.disconnect();
    observer = null;
    restore(root);
  }
}

export const currentLanguage = () => current;
